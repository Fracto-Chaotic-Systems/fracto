import fs from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { load_mapping_rows } from "./wordnet_mapping_seed.js";

export const NAME_SUGGESTIONS_MARKER = "World name suggestions (unapproved):";
export function parse_name_suggestions(text, mappings) {
  const by_card = new Map(mappings.map((row) => [row.cardinality, row]));
  const seen = new Set();
  const names = new Set();
  const rows = text
    .trim()
    .split(/\r?\n/)
    .map((line) => {
      const [card, theme, ...parts] = line
        .split("|")
        .map((part) => part.trim());
      const cardinality = Number(card);
      const mapping = by_card.get(cardinality);
      if (
        !mapping ||
        seen.has(cardinality) ||
        theme !== mapping.word ||
        parts.length < 2 ||
        parts.length > 6 ||
        parts.length % 2
      )
        throw Error(`Invalid or conflicting suggestion row: ${card}`);
      seen.add(cardinality);
      const suggestions = [];
      for (let index = 0; index < parts.length; index += 2) {
        const name = parts[index],
          reason = parts[index + 1];
        if (
          !name ||
          !reason ||
          names.has(name.toLowerCase()) ||
          name.length > 255
        )
          throw Error(`Missing or duplicate name/reason: ${card} ${name}`);
        names.add(name.toLowerCase());
        suggestions.push({ name, reason });
      }
      return { cardinality, synset_id: mapping.synset_id, theme, suggestions };
    });
  if (seen.size !== mappings.length)
    throw Error("Suggestions do not cover every mapping");
  return rows.sort((a, b) => a.cardinality - b.cardinality);
}
export function suggestion_note(row) {
  return `${NAME_SUGGESTIONS_MARKER}\n${row.suggestions.map(({ name, reason }) => `- ${name}: ${reason}`).join("\n")}`;
}
const sql_text = (value) =>
  `CONVERT(0x${Buffer.from(value, "utf8").toString("hex")} USING utf8mb4)`;
export function render_name_suggestions(rows) {
  if (!rows.length) throw Error("Empty suggestion seed");
  const select_rows = rows
    .map(
      (row) =>
        `SELECT ${row.cardinality} AS cardinality, ${sql_text(row.synset_id)} AS synset_id, ${sql_text(suggestion_note(row))} AS naming_notes`,
    )
    .join("\nUNION ALL\n");
  return `-- Append unapproved name proposals for ${rows.length} worlds; names and associations stay unchanged.
-- Generated by scripts/world_name_suggestions.js. Immutable after application.
-- Existing notes are retained, and the marker prevents duplicate additions on replay.
UPDATE wordnet_mappings AS mappings
JOIN (
${select_rows}
) AS proposals ON proposals.cardinality = mappings.cardinality AND proposals.synset_id = mappings.synset_id
SET mappings.notes = CONCAT(mappings.notes, IF(mappings.notes = '', '', ${sql_text("\n\n")}), proposals.naming_notes)
WHERE LOCATE(${sql_text(NAME_SUGGESTIONS_MARKER)}, mappings.notes) = 0;
`;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  if (!process.argv[2])
    throw Error(
      "Usage: node scripts/world_name_suggestions.js <new-migration.sql>",
    );
  const source = await fs.readFile(
    new URL("../database/seeds/world-name-suggestions-v1.txt", import.meta.url),
    "utf8",
  );
  const rows = parse_name_suggestions(source, await load_mapping_rows());
  await fs.writeFile(process.argv[2], render_name_suggestions(rows), {
    flag: "wx",
  });
  console.log(
    JSON.stringify({
      worlds: rows.length,
      suggestions: rows.reduce((sum, row) => sum + row.suggestions.length, 0),
      alternatives: rows.filter((row) => row.suggestions.length > 1).length,
    }),
  );
}
