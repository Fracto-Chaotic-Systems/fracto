import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function mapping_factorization(value) {
  const factors = [];
  let remainder = value;
  for (
    let prime = 2;
    prime <= remainder / prime;
    prime += prime === 2 ? 1 : 2
  ) {
    let exponent = 0;
    while (remainder % prime === 0) {
      remainder /= prime;
      exponent++;
    }
    if (exponent) factors.push(`${prime}${exponent > 1 ? `^${exponent}` : ""}`);
  }
  if (remainder > 1) factors.push(`${remainder}`);
  return factors.join(" x ") || "1";
}

export function build_mapping_rows(entries, contenders) {
  const by_id = new Map(contenders.map((item) => [item.id, item]));
  const cardinalities = new Set();
  const synsets = new Set();
  return [...entries]
    .sort((a, b) => a.cardinality - b.cardinality)
    .map((entry) => {
      const { cardinality, synset_id, label, note } = entry;
      if (!Number.isSafeInteger(cardinality) || cardinality < 1)
        throw new Error("Invalid mapping cardinality");
      if (!/^\d{8}$/.test(synset_id))
        throw new Error(`Invalid synset: ${synset_id}`);
      if (cardinalities.has(cardinality) || synsets.has(synset_id))
        throw new Error("Duplicate mapping cardinality or synset");
      const contender = by_id.get(synset_id);
      if (
        !contender ||
        contender.label !== label ||
        typeof contender.gloss !== "string" ||
        !contender.gloss.trim()
      )
        throw new Error(`Missing or mismatched source sense: ${synset_id}`);
      if (typeof note !== "string" || !note.trim())
        throw new Error(`Missing mapping note: ${cardinality}`);
      cardinalities.add(cardinality);
      synsets.add(synset_id);
      return {
        cardinality,
        synset_id,
        wordnet_version: "3.1",
        word: label,
        definition: contender.gloss.split(";")[0].trim(),
        gloss: contender.gloss,
        factorization: mapping_factorization(cardinality),
        notes: note,
      };
    });
}

export async function load_mapping_rows() {
  const base = path.join(root, "servers", "fracto-ui", "src", "pages", "games");
  const [first, gaps, compounds, contenders] = await Promise.all(
    [
      "WorldsFirstRound.js",
      "WorldsGapFill.js",
      "WorldsCompounds.js",
      "WorldsContenders.js",
    ].map((name) => import(pathToFileURL(path.join(base, name)).href)),
  );
  return build_mapping_rows(
    [
      ...first.WORLDS_FIRST_ROUND,
      ...gaps.WORLDS_GAP_FILL,
      ...compounds.WORLDS_COMPOUNDS,
    ],
    contenders.WORLD_CONTENDERS,
  );
}

// Hex UTF-8 literals preserve quotes, backslashes and Unicode independently of
// the connection charset and NO_BACKSLASH_ESCAPES SQL mode.
const sql_text = (value) =>
  `CONVERT(0x${Buffer.from(value, "utf8").toString("hex")} USING utf8mb4)`;
export function render_mapping_migration(rows, license) {
  if (!rows.length || !license.trim())
    throw new Error("Mapping seed and source license are required");
  const columns = [
    "cardinality",
    "synset_id",
    "wordnet_version",
    "word",
    "definition",
    "gloss",
    "factorization",
    "notes",
  ];
  const values = rows
    .map(
      (row) =>
        `  (${columns.map((column) => (column === "cardinality" ? row[column] : sql_text(row[column]))).join(", ")})`,
    )
    .join(",\n");
  return `-- Curated WordNet 3.1 worlds snapshot: ${rows.length} mappings.\n-- Generated by scripts/wordnet_mapping_seed.js; immutable after application.\n-- Reruns add missing rows and preserve existing mappings and notes.\n-- WordNet source license:\n${license
    .trimEnd()
    .split(/\r?\n/)
    .map((line) => `-- ${line}`)
    .join("\n")}\n
CREATE TABLE IF NOT EXISTS wordnet_mappings (
  cardinality BIGINT UNSIGNED NOT NULL,
  synset_id CHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  wordnet_version VARCHAR(16) NOT NULL DEFAULT '3.1',
  word VARCHAR(255) NOT NULL,
  definition TEXT NOT NULL,
  gloss TEXT NOT NULL,
  factorization VARCHAR(255) NOT NULL,
  notes TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (cardinality),
  UNIQUE KEY wordnet_mappings_synset_id (synset_id),
  CONSTRAINT wordnet_mappings_positive_cardinality CHECK (cardinality > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO wordnet_mappings (${columns.join(", ")}) VALUES
${values}
ON DUPLICATE KEY UPDATE cardinality = wordnet_mappings.cardinality;
`;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const output = process.argv[2];
  if (!output)
    throw new Error(
      "Usage: node scripts/wordnet_mapping_seed.js <new-migration.sql>",
    );
  const rows = await load_mapping_rows();
  const license = await fs.readFile(
    path.join(root, "servers", "fracto-ui", "public", "wordnet", "LICENSE.txt"),
    "utf8",
  );
  await fs.writeFile(
    path.resolve(output),
    render_mapping_migration(rows, license),
    { flag: "wx" },
  );
  console.log(
    `Wrote ${rows.length} mappings to ${output}; existing migration files are never overwritten.`,
  );
}
