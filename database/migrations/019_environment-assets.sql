-- Asset binaries remain in the environment library; this table indexes provenance.
CREATE TABLE IF NOT EXISTS environment_assets (
  asset_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  version VARCHAR(64) NOT NULL,
  category VARCHAR(64) NOT NULL,
  description TEXT NULL,
  parent_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  record_path VARCHAR(255) NOT NULL,
  model_path TEXT NULL,
  model_format VARCHAR(16) NULL,
  attribution_status VARCHAR(64) NOT NULL,
  creator_name TEXT NULL,
  creator_profile_url TEXT NULL,
  source_url TEXT NULL,
  license_name TEXT NULL,
  license_file TEXT NULL,
  credit_text TEXT NULL,
  modification_conditions TEXT NULL,
  redistribution_conditions TEXT NULL,
  notes TEXT NULL,
  sources JSON NOT NULL,
  modification_history JSON NOT NULL,
  revision CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY environment_assets_category (category),
  KEY environment_assets_attribution (attribution_status),
  KEY environment_assets_parent (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
